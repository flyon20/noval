CREATE TABLE IF NOT EXISTS ai_project_retrieval_eval_baseline (
    baseline_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    suite_name VARCHAR(100) NOT NULL,
    baseline_key VARCHAR(128) NOT NULL,
    generation_scope VARCHAR(64),
    cohort_json CLOB,
    metrics_json CLOB NOT NULL,
    confidence_json CLOB,
    gate_json CLOB,
    corpus_version VARCHAR(64) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    notes VARCHAR(500),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    deleted TINYINT NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_ai_project_retrieval_eval_baseline ON ai_project_retrieval_eval_baseline(suite_name, baseline_key);

CREATE TABLE IF NOT EXISTS ai_project_knowledge_feedback (
    feedback_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    project_id BIGINT NOT NULL,
    work_id BIGINT,
    generation_id BIGINT,
    conversation_id VARCHAR(128),
    trace_id VARCHAR(64),
    feedback_type VARCHAR(40) NOT NULL,
    target_type VARCHAR(40) NOT NULL,
    target_key VARCHAR(240) NOT NULL,
    old_value_json CLOB,
    new_value_json CLOB,
    evidence_json CLOB,
    operator_user_id BIGINT NOT NULL,
    review_status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    notes VARCHAR(500),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    deleted TINYINT NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_ai_project_knowledge_feedback_scope ON ai_project_knowledge_feedback(user_id, project_id, work_id, generation_id, deleted);

CREATE TABLE IF NOT EXISTS ai_agent_resource_diagnostic (
    diagnostic_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    project_id BIGINT,
    run_id VARCHAR(64),
    trace_id VARCHAR(64),
    generation_id BIGINT,
    partial_flush TINYINT NOT NULL DEFAULT 0,
    event_name VARCHAR(80),
    mysql_write_ms INT,
    tool_dedupe_prevented TINYINT NOT NULL DEFAULT 0,
    crawl_reuse TINYINT NOT NULL DEFAULT 0,
    vector_latency_ms INT,
    active_run_count INT,
    queue_wait_ms INT,
    degradation_reasons CLOB,
    payload_json CLOB,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_ai_agent_resource_diagnostic_trace ON ai_agent_resource_diagnostic(trace_id, created_at);
